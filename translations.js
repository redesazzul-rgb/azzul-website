// Función para cambiar de idioma
function setLanguage(lang) {
  // Guardar preferencia en localStorage
  localStorage.setItem('preferredLang', lang);
  
  // Establecer atributo lang en el elemento html
  document.documentElement.setAttribute('lang', lang);
  
  // Traducir todos los elementos con atributo data-i18n
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key] !== undefined) {
      const translationText = translations[lang][key];
      
      // Manejar placeholders si es input o textarea por tagName
      const tagName = element.tagName.toUpperCase();
      if (tagName === 'INPUT' || tagName === 'TEXTAREA') {
        element.placeholder = translationText;
      } else {
        element.innerHTML = translationText;
      }
    }
  });

  // Sincronizar botones de selector de idioma
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });
}

// Inicializar idioma en DOMContentLoaded
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('preferredLang') || 'es';
  setLanguage(savedLang);

  // Vincular eventos click en todos los botones del selector de idioma (.lang-btn)
  document.addEventListener('click', (e) => {
    const langBtn = e.target.closest('.lang-btn');
    if (langBtn) {
      const selectedLang = langBtn.getAttribute('data-lang');
      if (selectedLang) {
        setLanguage(selectedLang);
      }
    }
  });
});
